/**
 * One-off: V42 mapped the Lua weapon `Type` with a wrong table (Sword→Axe, Staff→Grenade Launcher…).
 * Writes Flyway migration V46 that rewrites item_weapon.subtype from the real 0-based Type.
 *
 *   set RF_LUA_ITEM_DIR=C:\path\to\luaScript\Item
 *   node backend/scripts/generate-weapon-subtype-fix.mjs
 */
import { readdirSync, readFileSync, writeFileSync } from 'fs'
import { dirname, join } from 'path'
import { fileURLToPath } from 'url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const migrationDir = join(__dirname, '..', 'src', 'main', 'resources', 'db', 'migration')
const LUA_ROOT =
  process.env.RF_LUA_ITEM_DIR ??
  'C:\\Users\\Wesley-PC\\Desktop\\rf-echelon-src\\ServerOutput\\luaScript\\Item'

// Same table as generate-guild-inventory-lua-details.mjs (indexed by Lua `Type`, 0-based).
const WEAPON_SUBTYPES = [
  'Knife', 'Sword', 'Axe', 'Mace', 'Spear', 'Bow',
  'Firearm', 'Launcher', 'Throwing Knife', 'Staff', 'Mining Tool', 'Grenade Launcher',
]

const dir = join(LUA_ROOT, 'Weapon')
const byCode = new Map()
for (const file of readdirSync(dir).filter((f) => f.toLowerCase().endsWith('.lua'))) {
  const content = readFileSync(join(dir, file), 'utf8')
  const code = content.match(/Code\s*=\s*"([^"]+)"/)?.[1]?.toLowerCase()
  const type = content.match(/\bType\s*=\s*(-?\d+)/)?.[1]
  const subtype = type != null ? WEAPON_SUBTYPES[Number(type)] : undefined
  if (code && subtype && !byCode.has(code)) byCode.set(code, subtype)
}

const values = [...byCode]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([code, subtype]) => `('${code.replace(/'/g, "''")}', '${subtype}')`)
  .join(',\n')

const sql = `-- Fix item_weapon.subtype: V42 used a wrong Lua Type table (generated by generate-weapon-subtype-fix.mjs).
-- Lua Type (0-based): ${WEAPON_SUBTYPES.map((s, i) => `${i}=${s}`).join(', ')}.

UPDATE item_weapon w
SET subtype = v.subtype
FROM item i
JOIN (VALUES
${values}
) AS v(game_code, subtype) ON LOWER(i.game_code) = v.game_code
WHERE w.item_id = i.id AND w.subtype <> v.subtype;
`

const outPath = join(migrationDir, 'V46__fix_weapon_subtype_from_lua_type.sql')
writeFileSync(outPath, sql)
console.log(`Wrote ${outPath} (${byCode.size} weapon codes)`)
